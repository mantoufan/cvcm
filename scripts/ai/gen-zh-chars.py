#!/usr/bin/env python3
"""Write src/client/ai/zh-chars.ts: one-to-one Traditional ↔ Simplified character pairs from OpenCC (Apache-2.0).

Whisper writes Chinese in either script; the speech-to-text page converts to the reader's. Character-level only
(no phrase table): enough for transcripts, and a few KB. Usage: gen-zh-chars.py TSCharacters.txt STCharacters.txt
"""
import sys


def pairs(path):
    out = []
    for line in open(path, encoding="utf-8"):
        if not line.strip() or line.startswith("#"):
            continue
        key, values = line.rstrip("\n").split("\t")
        value = values.split(" ")[0]
        if len(key) == 1 and len(value) == 1 and key != value:
            out.append(key + value)
    return "".join(out)


t2s, s2t = pairs(sys.argv[1]), pairs(sys.argv[2])
with open("src/client/ai/zh-chars.ts", "w", encoding="utf-8") as f:
    f.write("// Generated by scripts/ai/gen-zh-chars.py from OpenCC TSCharacters / STCharacters (Apache-2.0). Do not edit.\n")
    f.write("// Each string is pairs of characters: from, to.\n")
    f.write(f'export const T2S = "{t2s}";\n')
    f.write(f'export const S2T = "{s2t}";\n')
print(len(t2s) // 2, "T→S pairs,", len(s2t) // 2, "S→T pairs")
