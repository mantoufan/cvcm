"""Build src/shared/font-metrics.ts: advance widths (1/1000 em) and Word's single line height for the fonts the
words-to-pages tool offers. Needs fontTools (pip install fonttools), macOS system fonts and Microsoft Word
(Calibri, Aptos and Cambria ship inside Word.app). Run: python3 scripts/gen-font-metrics.py

Word's "single" line is the font's hhea ascent + descent + line gap: 1.15 em for Times New Roman, 1.22 for Calibri."""
import json
from pathlib import Path

from fontTools.ttLib import TTCollection, TTFont

ROOT = Path(__file__).resolve().parent.parent
SUP = "/System/Library/Fonts/Supplemental/"
WORD = "/Applications/Microsoft Word.app/Contents/Resources/DFonts/"
FONTS = {
    "times": (SUP + "Times New Roman.ttf", None),
    "arial": (SUP + "Arial.ttf", None),
    "calibri": (WORD + "Calibri.ttf", None),
    "aptos": (WORD + "Aptos.ttf", None),
    "cambria": (WORD + "Cambria.ttc", 0),
    "georgia": (SUP + "Georgia.ttf", None),
    "verdana": (SUP + "Verdana.ttf", None),
    "courier": (SUP + "Courier New.ttf", None),
}
EXTRA = "‘’“”–—…éèáàíóúñüöäçß"

out = {}
for key, (path, index) in FONTS.items():
    font = TTCollection(path).fonts[index] if index is not None else TTFont(path)
    upm = font["head"].unitsPerEm
    cmap = font.getBestCmap()
    hmtx = font["hmtx"].metrics
    hhea = font["hhea"]
    width = lambda c: round(hmtx[cmap[ord(c)]][0] * 1000 / upm)
    out[key] = {
        "name": font["name"].getDebugName(1),
        "line": round((hhea.ascent - hhea.descent + hhea.lineGap) / upm, 4),
        # Characters 32–126 in order, as one comma list to keep the module small.
        "ascii": ",".join(str(width(chr(c))) for c in range(32, 127)),
        "extra": {c: width(c) for c in EXTRA if ord(c) in cmap},
    }

lines = ["// Generated by scripts/gen-font-metrics.py from the font files. Do not edit.",
         "/** Advance widths in 1/1000 em (ASCII 32–126 as a comma list, plus a few typographic characters) and Word's single line height in em. */",
         "export const FONT_METRICS = {"]
for key, m in out.items():
    lines.append(f"  {key}: {{ name: {json.dumps(m['name'])}, line: {m['line']}, ascii: {json.dumps(m['ascii'])}, extra: {json.dumps(m['extra'], ensure_ascii=False)} }},")
lines.append("} as const;")
(ROOT / "src/shared/font-metrics.ts").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("wrote", ", ".join(f"{k} {m['line']}" for k, m in out.items()))
