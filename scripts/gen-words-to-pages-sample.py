"""Build src/shared/words-to-pages-sample.ts: about 2,000 words of the site's own English prose (knowledge articles),
in essay-length paragraphs. The words-to-pages tool lays this text out to estimate words per page from a bare word count.
Run: python3 scripts/gen-words-to-pages-sample.py"""
import glob
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
paras = []
for f in sorted(glob.glob(str(ROOT / "src/locales/kb/en/*.json"))):
    for s in json.loads(Path(f).read_text(encoding="utf-8")).get("sections", []):
        for b in s.get("body", []):
            # Plain prose only: no code, tables, URLs or long numbers.
            if isinstance(b, str) and len(b.split()) >= 45 and not re.search(r"[{}();=<>`\[\]_#|*/\\$]|\d{3,}", b):
                paras.append(" ".join(b.split()))
picked = paras[::8]
# Pairs make ~115-word paragraphs, close to an essay's.
merged = [" ".join(picked[i:i + 2]) for i in range(0, len(picked), 2)]
text = "\n".join(merged)
words = len(text.split())
out = ROOT / "src/shared/words-to-pages-sample.ts"
out.write_text(
    "// Generated by scripts/gen-words-to-pages-sample.py from the knowledge articles (src/locales/kb/en). Do not edit.\n"
    f"/** {words} words of plain English prose in {len(merged)} paragraphs, one per line. */\n"
    f"export const SAMPLE_TEXT = {json.dumps(text, ensure_ascii=False)};\n",
    encoding="utf-8",
)
print(f"{words} words, {len(merged)} paragraphs, {len(text)} chars")
