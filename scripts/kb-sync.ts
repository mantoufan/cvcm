// `npm run kb:sync`: after editing knowledge copy, refresh src/locales/kb/meta.json (last-changed date, fingerprint and
// reading time per article) and src/locales/kb/all.ts (static imports for the Worker and tests).
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { KB_ARTICLES } from "../src/shared/kb";
import type { KbArticleCopy } from "../src/shared/kb-i18n";
import { syncEntry, type KbSyncEntry } from "../src/shared/kb-sync";
import { LOCALES, type Locale } from "../src/shared/locale";

const dir = resolve(process.cwd(), "src/locales/kb");
const metaPath = resolve(dir, "meta.json");
const previous: Record<string, KbSyncEntry> = existsSync(metaPath) ? JSON.parse(readFileSync(metaPath, "utf8")) : {};
const today = process.env.KB_TODAY ?? new Date().toISOString().slice(0, 10);

const meta: Record<string, KbSyncEntry> = {};
const changed: string[] = [];
for (const id of KB_ARTICLES) {
  const copies = Object.fromEntries(LOCALES.map((locale) => [locale, JSON.parse(readFileSync(resolve(dir, locale, `${id}.json`), "utf8"))])) as Record<Locale, KbArticleCopy>;
  meta[id] = syncEntry(copies, previous[id], today);
  if (!previous[id] || previous[id].updated !== meta[id].updated) changed.push(id);
}
writeFileSync(metaPath, JSON.stringify(meta, null, 2) + "\n");

const name = (locale: string, id: string): string => `${locale.replace("-", "")}_${id.replace(/-/g, "_")}`;
const lines = [
  "// Generated by `npm run kb:sync`. Every article in every locale, for the Worker and tests; the client loads one at a time.",
  ...LOCALES.flatMap((locale) => KB_ARTICLES.map((id) => `import ${name(locale, id)} from "./${locale}/${id}.json";`)),
  'import type { KbArticleCopy } from "../../shared/kb-i18n";',
  'import type { KbId } from "../../shared/kb";',
  'import type { Locale } from "../../shared/locale";',
  "",
  "export const KB_ALL = {",
  ...LOCALES.map((locale) => `  ${JSON.stringify(locale)}: { ${KB_ARTICLES.map((id) => `${JSON.stringify(id)}: ${name(locale, id)}`).join(", ")} },`),
  "} as unknown as Record<Locale, Record<KbId, KbArticleCopy>>;",
  "",
];
writeFileSync(resolve(dir, "all.ts"), lines.join("\n"));

// Plain dynamic imports (not import.meta.glob): the prerender bundles the client with esbuild, which has no glob.
const loaders = [
  "// Generated by `npm run kb:sync`. One lazy chunk per article and locale, for the client.",
  'import type { KbArticleCopy } from "../../shared/kb-i18n";',
  'import type { KbId } from "../../shared/kb";',
  'import type { Locale } from "../../shared/locale";',
  "",
  "type Load = () => Promise<{ default: unknown }>;",
  "",
  "export const KB_LOADERS = {",
  ...LOCALES.map((locale) => `  ${JSON.stringify(locale)}: {\n${KB_ARTICLES.map((id) => `    ${JSON.stringify(id)}: () => import("./${locale}/${id}.json"),`).join("\n")}\n  },`),
  "} as Record<Locale, Record<KbId, Load>> as unknown as Record<Locale, Record<KbId, () => Promise<{ default: KbArticleCopy }>>>;",
  "",
];
writeFileSync(resolve(dir, "loaders.ts"), loaders.join("\n"));
console.log(changed.length ? `kb:sync: updated ${changed.join(", ")} -> ${today}` : "kb:sync: no copy changes");
