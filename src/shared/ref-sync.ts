import { LOCALES, type Locale } from "./locale";
import { REF_ENTRIES } from "./ref";

/**
 * What `npm run ref:sync` writes, as { path relative to the repo root: file content }. Pure, so tests/ref.test.ts
 * can rebuild the same files and fail when the committed copies are stale. A locale file that does not exist yet
 * falls back to English here (the sync warns); tests/ref.test.ts still requires every locale × entry on disk.
 *
 * - `src/locales/ref/index/<locale>.json`: every entry's name and blurb, so hub lists and related links need no entry chunk
 * - `src/locales/ref/names.json`: each entry's name in every locale (the entry page's names table)
 * - `src/locales/ref/all.ts`: every entry in every locale, for the Worker, prerender and tests
 * - `src/locales/ref/loaders/<locale>.ts`: one lazy chunk per entry, for the client
 * - `src/locales/packs/ref-<locale>.ts`: the reference pack (hub copy + list + names + src/data/ref-photos.json), loaded only on reference pages
 */
export function refSyncFiles(read: (path: string) => string | null): { files: Record<string, string>; missing: string[] } {
  const files: Record<string, string> = {};
  const missing: string[] = [];
  const header = "// Generated by `npm run ref:sync`; do not edit.";

  /** Which locale's file stands in for `<locale>/<id>.json` (or `<locale>.json` when id is null). */
  const sourceLocale = (locale: Locale, id: string | null): Locale => {
    const path = id ? `src/locales/ref/${locale}/${id}.json` : `src/locales/ref/${locale}.json`;
    if (locale === "en" || read(path) !== null) return locale;
    missing.push(path);
    return "en";
  };
  const entryOf = (locale: Locale, id: string): { name: string; blurb: string } => {
    const text = read(`src/locales/ref/${locale}/${id}.json`);
    if (text === null) throw new Error(`ref:sync: missing src/locales/ref/${locale}/${id}.json`);
    const copy = JSON.parse(text) as { name: string; blurb: string };
    return { name: copy.name, blurb: copy.blurb };
  };

  const sources = Object.fromEntries(LOCALES.map((locale) => [locale, Object.fromEntries(REF_ENTRIES.map((id) => [id, sourceLocale(locale, id)]))])) as Record<Locale, Record<string, Locale>>;
  const names: Record<string, Record<string, string>> = {};
  for (const locale of LOCALES) {
    const list = Object.fromEntries(REF_ENTRIES.map((id) => [id, entryOf(sources[locale][id], id)]));
    files[`src/locales/ref/index/${locale}.json`] = JSON.stringify(list, null, 2) + "\n";
    for (const id of REF_ENTRIES) (names[id] ??= {})[locale] = list[id].name;
  }
  files["src/locales/ref/names.json"] = JSON.stringify(names, null, 2) + "\n";

  const ident = (locale: string, id: string): string => `${locale.replace("-", "")}_${id.replace(/-/g, "_")}`;
  files["src/locales/ref/all.ts"] = [
    `${header} Every entry in every locale, for the Worker, prerender and tests; the client loads one at a time.`,
    ...LOCALES.flatMap((locale) => REF_ENTRIES.map((id) => `import ${ident(locale, id)} from "./${sources[locale][id]}/${id}.json";`)),
    'import type { RefEntryCopy } from "../../shared/ref-i18n";',
    'import type { RefId } from "../../shared/ref";',
    'import type { Locale } from "../../shared/locale";',
    "",
    "const all = {",
    ...LOCALES.map((locale) => `  ${JSON.stringify(locale)}: { ${REF_ENTRIES.map((id) => `${JSON.stringify(id)}: ${ident(locale, id)}`).join(", ")} },`),
    "} satisfies Record<Locale, Record<RefId, unknown>>;",
    "",
    "// JSON imports type each block union loosely; the shape is checked by tests/ref.test.ts.",
    "export const REF_ALL = all as unknown as Record<Locale, Record<RefId, RefEntryCopy>>;",
    "",
  ].join("\n");

  // Plain dynamic imports (not import.meta.glob): the prerender bundles the client with esbuild, which has no glob.
  for (const locale of LOCALES) {
    files[`src/locales/ref/loaders/${locale}.ts`] = [
      `${header} One lazy chunk per reference entry in this locale, for the client.`,
      'import type { RefId } from "../../../shared/ref";',
      "",
      "export const REF_LOADERS = {",
      ...REF_ENTRIES.map((id) => `  ${JSON.stringify(id)}: () => import("../${sources[locale][id]}/${id}.json"),`),
      "} satisfies Record<RefId, () => Promise<unknown>>;",
      "",
    ].join("\n");
    files[`src/locales/packs/ref-${locale}.ts`] = [
      `${header} Reference hub copy, entry names and blurbs, loaded only on /reference/ pages.`,
      `import hub from "../ref/${sourceLocale(locale, null)}.json";`,
      `import list from "../ref/index/${locale}.json";`,
      'import names from "../ref/names.json";',
      'import photos from "../../data/ref-photos.json";',
      'import type { RefMessages } from "../../shared/messages";',
      "",
      "export default { ...hub, list, names, photos } satisfies RefMessages;",
      "",
    ].join("\n");
  }
  return { files, missing: [...new Set(missing)] };
}
