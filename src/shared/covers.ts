/**
 * Where covers are served: the s3.cv.cm bucket, not the Worker's assets. Paths in this file stay "/covers/…" (the dev
 * server serves them from public/); production builds rewrite them to this origin (scripts/cover-origin.mjs).
 */
export const COVER_ORIGIN = "https://s3.cv.cm/files";

/** Absolute URL of a cover, for og:image, JSON-LD and sitemaps. */
export function coverUrl(path: string): string {
  const bare = path.split("?")[0];
  return bare.startsWith("/") ? `${COVER_ORIGIN}${bare}` : bare;
}

/** English diagrams live in /covers/tutorials/. Other locales use /covers/tutorials/{locale}/. */
export function localizedTutorialSrc(src: string, locale: Locale): string {
  if (locale === "en" || !src.startsWith("/covers/tutorials/")) return src;
  const rest = src.slice("/covers/tutorials/".length);
  if (rest.includes("/")) return src;
  return `/covers/tutorials/${localePath(locale)}/${rest}`;
}

/** Widths of the WebP cover thumbnails earlier builds served at /thumbs/{width}/. None are built now. */
export const THUMB_WIDTHS = [240, 640, 960] as const;

const THUMB_PATH = new RegExp(`^/thumbs/(?:${THUMB_WIDTHS.join("|")})/([A-Za-z0-9._/-]+?\\.(?:jpe?g|png))(?:\\.v(\\d+))?\\.webp$`);

/** Original cover path for a legacy /thumbs/ URL; the Worker redirects there. */
export function thumbOriginal(pathname: string): string | null {
  const m = THUMB_PATH.exec(pathname);
  if (!m || m[1].includes("..")) return null;
  return `/covers/${m[1]}${m[2] ? `?v=${m[2]}` : ""}`;
}
