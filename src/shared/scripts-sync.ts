import { LOCALES, type Locale } from "./locale";
import { SCRIPT_ENTRIES } from "./scripts";

/**
 * What `npm run scripts:sync` writes, as { path relative to the repo root: file content }. Pure, so
 * tests/scripts.test.ts can rebuild the same files and fail when the committed copies are stale. A locale file that
 * does not exist yet falls back to English here (the sync warns); an entry with no English master stops the sync
 * with an error. The test still requires every locale × work on disk.
 *
 * - `src/locales/scripts/index/<locale>.json`: every entry's name and blurb (and an idea list's count), so hub lists and related links need no entry chunk
 * - `src/locales/scripts/all.ts`: every entry in every locale, for the Worker, prerender and tests
 * - `src/locales/scripts/loaders/<locale>.ts`: one lazy chunk per entry, for the client
 * - `src/locales/packs/scripts-<locale>.ts`: the scripts pack (hub copy + list + meta), loaded only on scripts pages
 */
export function scriptsSyncFiles(read: (path: string) => string | null): { files: Record<string, string>; missing: string[] } {
  const files: Record<string, string> = {};
  const missing: string[] = [];
  const header = "// Generated by `npm run scripts:sync`; do not edit.";

  // Every catalogued entry needs its English master: the hub, routes and sitemap list every id, so a gap would break pages.
  for (const id of SCRIPT_ENTRIES) {
    if (read(`src/locales/scripts/en/${id}.json`) === null) throw new Error(`scripts:sync: missing src/locales/scripts/en/${id}.json`);
  }
  /** Which locale's file stands in for `<locale>/<id>.json` (or `<locale>.json` when id is null). */
  const sourceLocale = (locale: Locale, id: string | null): Locale => {
    const path = id ? `src/locales/scripts/${locale}/${id}.json` : `src/locales/scripts/${locale}.json`;
    if (locale === "en" || read(path) !== null) return locale;
    missing.push(path);
    return "en";
  };
  // Idea lists also carry their idea count, so hub and related links can say "48 ideas" without the entry chunk.
  const entryOf = (locale: Locale, id: string): { name: string; blurb: string; ideas?: number } => {
    const copy = JSON.parse(read(`src/locales/scripts/${locale}/${id}.json`)!) as { name: string; blurb: string; groups?: { items: unknown[] }[] };
    return { name: copy.name, blurb: copy.blurb, ...(copy.groups ? { ideas: copy.groups.reduce((n, g) => n + g.items.length, 0) } : {}) };
  };

  const sources = Object.fromEntries(LOCALES.map((locale) => [locale, Object.fromEntries(SCRIPT_ENTRIES.map((id) => [id, sourceLocale(locale, id)]))])) as Record<Locale, Record<string, Locale>>;
  for (const locale of LOCALES) {
    const list = Object.fromEntries(SCRIPT_ENTRIES.map((id) => [id, entryOf(sources[locale][id], id)]));
    files[`src/locales/scripts/index/${locale}.json`] = JSON.stringify(list, null, 2) + "\n";
  }

  const ident = (locale: string, id: string): string => `${locale.replace("-", "")}_${id.replace(/-/g, "_")}`;
  files["src/locales/scripts/all.ts"] = [
    `${header} Every entry in every locale, for the Worker, prerender and tests; the client loads one at a time.`,
    ...LOCALES.flatMap((locale) => SCRIPT_ENTRIES.map((id) => `import ${ident(locale, id)} from "./${sources[locale][id]}/${id}.json";`)),
    'import type { ScriptEntryCopy } from "../../shared/scripts-i18n";',
    'import type { ScriptId } from "../../shared/scripts";',
    'import type { Locale } from "../../shared/locale";',
    "",
    "const all = {",
    ...LOCALES.map((locale) => `  ${JSON.stringify(locale)}: { ${SCRIPT_ENTRIES.map((id) => `${JSON.stringify(id)}: ${ident(locale, id)}`).join(", ")} },`),
    "} satisfies Record<Locale, Record<ScriptId, unknown>>;",
    "",
    "// JSON imports type each block union loosely; the shape is checked by tests/scripts.test.ts.",
    "export const SCRIPTS_ALL = all as unknown as Record<Locale, Record<ScriptId, ScriptEntryCopy>>;",
    "",
  ].join("\n");

  // Plain dynamic imports (not import.meta.glob): the prerender bundles the client with esbuild, which has no glob.
  for (const locale of LOCALES) {
    files[`src/locales/scripts/loaders/${locale}.ts`] = [
      `${header} One lazy chunk per scripts entry in this locale, for the client.`,
      'import type { ScriptId } from "../../../shared/scripts";',
      "",
      "export const SCRIPT_LOADERS = {",
      ...SCRIPT_ENTRIES.map((id) => `  ${JSON.stringify(id)}: () => import("../${sources[locale][id]}/${id}.json"),`),
      "} satisfies Record<ScriptId, () => Promise<unknown>>;",
      "",
    ].join("\n");
    files[`src/locales/packs/scripts-${locale}.ts`] = [
      `${header} Scripts hub copy, entry names and blurbs, loaded only on /scripts/ pages.`,
      `import hub from "../scripts/${sourceLocale(locale, null)}.json";`,
      `import list from "../scripts/index/${locale}.json";`,
      // Cast, runtime, genres, format, uses and related ids ride in the pack (one shared chunk), not the entry bundle.
      'import meta from "../../shared/scripts-meta.json";',
      'import type { ScriptsMessages } from "../../shared/messages";',
      'import type { ScriptMeta } from "../../shared/scripts-meta";',
      'import type { ScriptId } from "../../shared/scripts";',
      "",
      "export default {",
      "  ...hub,",
      "  list: list as Record<ScriptId, { name: string; blurb: string; ideas?: number }>,",
      "  meta: meta as unknown as Record<ScriptId, ScriptMeta>,",
      "} satisfies ScriptsMessages;",
      "",
    ].join("\n");
  }
  return { files, missing: [...new Set(missing)] };
}
