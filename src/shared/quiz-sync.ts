import { LOCALES } from "./locale";
import { QUIZZES } from "./quiz";

/**
 * What `npm run quiz:sync` writes, as { path relative to the repo root: file content }. Pure, so tests/quiz.test.ts
 * can rebuild the same files and fail when the committed copies are stale. Every test's copy lives in
 * `src/locales/quiz/<locale>/<id>.json`; the sync fails if one is missing (there is no English stand-in for a test).
 *
 * - `src/locales/quiz/all.ts`: every test in every locale, for the Worker, prerender and tests
 * - `src/locales/quiz/loaders/<locale>.ts`: one lazy chunk per test, for the client
 */
export function quizSyncFiles(read: (path: string) => string | null): Record<string, string> {
  const files: Record<string, string> = {};
  const header = "// Generated by `npm run quiz:sync`; do not edit.";
  for (const locale of LOCALES) {
    for (const id of QUIZZES) {
      if (read(`src/locales/quiz/${locale}/${id}.json`) === null) throw new Error(`quiz:sync: missing src/locales/quiz/${locale}/${id}.json`);
    }
  }
  const ident = (locale: string, id: string): string => `${locale.replace("-", "")}_${id.replace(/-/g, "_")}`;
  files["src/locales/quiz/all.ts"] = [
    `${header} Every test in every locale, for the Worker, prerender and tests; the client loads one at a time.`,
    ...LOCALES.flatMap((locale) => QUIZZES.map((id) => `import ${ident(locale, id)} from "./${locale}/${id}.json";`)),
    'import type { QuizCopy } from "../../shared/quiz-i18n";',
    'import type { QuizId } from "../../shared/quiz";',
    'import type { Locale } from "../../shared/locale";',
    "",
    "const all = {",
    ...LOCALES.map((locale) => `  ${JSON.stringify(locale)}: { ${QUIZZES.map((id) => `${JSON.stringify(id)}: ${ident(locale, id)}`).join(", ")} },`),
    "} satisfies Record<Locale, Record<QuizId, unknown>>;",
    "",
    "// Each test has its own optional parts, so JSON imports type them loosely; tests/quiz.test.ts checks the shape.",
    "export const QUIZ_ALL = all as unknown as Record<Locale, Record<QuizId, QuizCopy>>;",
    "",
  ].join("\n");
  // Plain dynamic imports (not import.meta.glob): the prerender bundles the client with esbuild, which has no glob.
  for (const locale of LOCALES) {
    files[`src/locales/quiz/loaders/${locale}.ts`] = [
      `${header} One lazy chunk per test in this locale, for the client.`,
      'import type { QuizId } from "../../../shared/quiz";',
      "",
      "export const QUIZ_LOADERS = {",
      ...QUIZZES.map((id) => `  ${JSON.stringify(id)}: () => import("../${locale}/${id}.json"),`),
      "} satisfies Record<QuizId, () => Promise<unknown>>;",
      "",
    ].join("\n");
  }
  return files;
}
