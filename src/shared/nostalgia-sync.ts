import { LOCALES, type Locale } from "./locale";
import { NOSTALGIA_ENTRIES } from "./nostalgia";

/**
 * What `npm run nostalgia:sync` writes, as { path relative to the repo root: file content }. Pure, so
 * tests/nostalgia.test.ts can rebuild the same files and fail when the committed copies are stale. A locale file that
 * does not exist yet falls back to English here (the sync warns); the test still requires every locale × entry on disk.
 *
 * - `src/locales/nostalgia/index/<locale>.json`: every entry's name and blurb, so hub lists and related links need no entry chunk
 * - `src/locales/nostalgia/all.ts`: every entry in every locale, for the Worker, prerender and tests
 * - `src/locales/nostalgia/loaders/<locale>.ts`: one lazy chunk per entry, for the client
 * - `src/locales/packs/nostalgia-<locale>.ts`: the nostalgia pack (hub copy + list + meta), loaded only on nostalgia pages
 */
export function nostalgiaSyncFiles(read: (path: string) => string | null): { files: Record<string, string>; missing: string[] } {
  const files: Record<string, string> = {};
  const missing: string[] = [];
  const header = "// Generated by `npm run nostalgia:sync`; do not edit.";

  /** Which locale's file stands in for `<locale>/<id>.json` (or `<locale>.json` when id is null). */
  const sourceLocale = (locale: Locale, id: string | null): Locale => {
    const path = id ? `src/locales/nostalgia/${locale}/${id}.json` : `src/locales/nostalgia/${locale}.json`;
    if (locale === "en" || read(path) !== null) return locale;
    missing.push(path);
    return "en";
  };
  const entryOf = (locale: Locale, id: string): { name: string; blurb: string } => {
    const text = read(`src/locales/nostalgia/${locale}/${id}.json`);
    if (text === null) throw new Error(`nostalgia:sync: missing src/locales/nostalgia/${locale}/${id}.json`);
    const copy = JSON.parse(text) as { name: string; blurb: string };
    return { name: copy.name, blurb: copy.blurb };
  };

  const sources = Object.fromEntries(LOCALES.map((locale) => [locale, Object.fromEntries(NOSTALGIA_ENTRIES.map((id) => [id, sourceLocale(locale, id)]))])) as Record<Locale, Record<string, Locale>>;
  for (const locale of LOCALES) {
    const list = Object.fromEntries(NOSTALGIA_ENTRIES.map((id) => [id, entryOf(sources[locale][id], id)]));
    files[`src/locales/nostalgia/index/${locale}.json`] = JSON.stringify(list, null, 2) + "\n";
  }

  const ident = (locale: string, id: string): string => `${locale.replace("-", "")}_${id.replace(/-/g, "_")}`;
  files["src/locales/nostalgia/all.ts"] = [
    `${header} Every entry in every locale, for the Worker, prerender and tests; the client loads one at a time.`,
    ...LOCALES.flatMap((locale) => NOSTALGIA_ENTRIES.map((id) => `import ${ident(locale, id)} from "./${sources[locale][id]}/${id}.json";`)),
    'import type { NostalgiaEntryCopy } from "../../shared/nostalgia-i18n";',
    'import type { NostalgiaId } from "../../shared/nostalgia";',
    'import type { Locale } from "../../shared/locale";',
    "",
    "const all = {",
    ...LOCALES.map((locale) => `  ${JSON.stringify(locale)}: { ${NOSTALGIA_ENTRIES.map((id) => `${JSON.stringify(id)}: ${ident(locale, id)}`).join(", ")} },`),
    "} satisfies Record<Locale, Record<NostalgiaId, unknown>>;",
    "",
    "// JSON imports type each block union loosely; the shape is checked by tests/nostalgia.test.ts.",
    "export const NOSTALGIA_ALL = all as unknown as Record<Locale, Record<NostalgiaId, NostalgiaEntryCopy>>;",
    "",
  ].join("\n");

  // Plain dynamic imports (not import.meta.glob): the prerender bundles the client with esbuild, which has no glob.
  for (const locale of LOCALES) {
    files[`src/locales/nostalgia/loaders/${locale}.ts`] = [
      `${header} One lazy chunk per nostalgia entry in this locale, for the client.`,
      'import type { NostalgiaId } from "../../../shared/nostalgia";',
      "",
      "export const NOSTALGIA_LOADERS = {",
      ...NOSTALGIA_ENTRIES.map((id) => `  ${JSON.stringify(id)}: () => import("../${sources[locale][id]}/${id}.json"),`),
      "} satisfies Record<NostalgiaId, () => Promise<unknown>>;",
      "",
    ].join("\n");
    files[`src/locales/packs/nostalgia-${locale}.ts`] = [
      `${header} Nostalgia hub copy, entry names and blurbs, loaded only on /nostalgia/ pages.`,
      `import hub from "../nostalgia/${sourceLocale(locale, null)}.json";`,
      `import list from "../nostalgia/index/${locale}.json";`,
      // Years, status, related ids and sources ride in the pack (one shared chunk), not the entry bundle.
      'import meta from "../../shared/nostalgia-meta.json";',
      'import type { NostalgiaMessages } from "../../shared/messages";',
      'import type { NostalgiaMeta } from "../../shared/nostalgia-meta";',
      'import type { NostalgiaId } from "../../shared/nostalgia";',
      "",
      "export default { ...hub, list, meta: meta as unknown as Record<NostalgiaId, NostalgiaMeta> } satisfies NostalgiaMessages;",
      "",
    ].join("\n");
  }
  return { files, missing: [...new Set(missing)] };
}
