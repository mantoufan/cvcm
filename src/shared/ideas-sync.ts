import { LOCALES, type Locale } from "./locale";
import { IDEA_ENTRIES } from "./ideas";

/**
 * What `npm run ideas:sync` writes, as { path relative to the repo root: file content }. Pure, so tests/ideas.test.ts
 * can rebuild the same files and fail when the committed copies are stale. A locale file that does not exist yet
 * falls back to English here (the sync warns); tests/ideas.test.ts still requires every locale × idea on disk.
 *
 * - `src/locales/ideas/index/<locale>.json`: every idea's name and blurb, so hub lists and related links need no idea chunk
 * - `src/locales/ideas/all.ts`: every idea in every locale, for the Worker, prerender and tests
 * - `src/locales/ideas/loaders/<locale>.ts`: one lazy chunk per idea, for the client
 * - `src/locales/packs/ideas-<locale>.ts`: the ideas pack (hub copy + list + data snapshot), loaded only on ideas pages
 */
export function ideasSyncFiles(read: (path: string) => string | null): { files: Record<string, string>; missing: string[] } {
  const files: Record<string, string> = {};
  const missing: string[] = [];
  const header = "// Generated by `npm run ideas:sync`; do not edit.";

  /** Which locale's file stands in for `<locale>/<id>.json` (or `<locale>.json` when id is null). */
  const sourceLocale = (locale: Locale, id: string | null): Locale => {
    const path = id ? `src/locales/ideas/${locale}/${id}.json` : `src/locales/ideas/${locale}.json`;
    if (locale === "en" || read(path) !== null) return locale;
    missing.push(path);
    return "en";
  };
  const entryOf = (locale: Locale, id: string): { name: string; blurb: string } => {
    const text = read(`src/locales/ideas/${locale}/${id}.json`);
    if (text === null) throw new Error(`ideas:sync: missing src/locales/ideas/${locale}/${id}.json`);
    const copy = JSON.parse(text) as { name: string; blurb: string };
    return { name: copy.name, blurb: copy.blurb };
  };

  const sources = Object.fromEntries(LOCALES.map((locale) => [locale, Object.fromEntries(IDEA_ENTRIES.map((id) => [id, sourceLocale(locale, id)]))])) as Record<Locale, Record<string, Locale>>;
  for (const locale of LOCALES) {
    const list = Object.fromEntries(IDEA_ENTRIES.map((id) => [id, entryOf(sources[locale][id], id)]));
    files[`src/locales/ideas/index/${locale}.json`] = JSON.stringify(list, null, 2) + "\n";
  }

  // Identifiers cannot start with a digit ("3d-printing"), so every one gets a prefix.
  const ident = (locale: string, id: string): string => `i_${locale.replace("-", "")}_${id.replace(/-/g, "_")}`;
  files["src/locales/ideas/all.ts"] = [
    `${header} Every idea in every locale, for the Worker, prerender and tests; the client loads one at a time.`,
    ...LOCALES.flatMap((locale) => IDEA_ENTRIES.map((id) => `import ${ident(locale, id)} from "./${sources[locale][id]}/${id}.json";`)),
    'import type { IdeaEntryCopy } from "../../shared/ideas-i18n";',
    'import type { IdeaId } from "../../shared/ideas";',
    'import type { Locale } from "../../shared/locale";',
    "",
    "const all = {",
    ...LOCALES.map((locale) => `  ${JSON.stringify(locale)}: { ${IDEA_ENTRIES.map((id) => `${JSON.stringify(id)}: ${ident(locale, id)}`).join(", ")} },`),
    "} satisfies Record<Locale, Record<IdeaId, unknown>>;",
    "",
    "// JSON imports type each block union loosely; the shape is checked by tests/ideas.test.ts.",
    "export const IDEAS_ALL = all as unknown as Record<Locale, Record<IdeaId, IdeaEntryCopy>>;",
    "",
  ].join("\n");

  // Plain dynamic imports (not import.meta.glob): the prerender bundles the client with esbuild, which has no glob.
  for (const locale of LOCALES) {
    files[`src/locales/ideas/loaders/${locale}.ts`] = [
      `${header} One lazy chunk per idea in this locale, for the client.`,
      'import type { IdeaId } from "../../../shared/ideas";',
      "",
      "export const IDEA_LOADERS = {",
      ...IDEA_ENTRIES.map((id) => `  ${JSON.stringify(id)}: () => import("../${sources[locale][id]}/${id}.json"),`),
      "} satisfies Record<IdeaId, () => Promise<unknown>>;",
      "",
    ].join("\n");
    files[`src/locales/packs/ideas-${locale}.ts`] = [
      `${header} Ideas hub copy, idea names and blurbs, and the search-data snapshot, loaded only on /ideas/ pages.`,
      `import hub from "../ideas/${sourceLocale(locale, null)}.json";`,
      `import list from "../ideas/index/${locale}.json";`,
      // The monthly snapshot rides in the ideas pack, not the main bundle, which it would re-hash on every refresh.
      'import data from "../../shared/ideas-data.json";',
      'import type { IdeasMessages } from "../../shared/messages";',
      'import type { IdeasData } from "../../shared/ideas-i18n";',
      "",
      "export default { ...hub, list, data: data as IdeasData } satisfies IdeasMessages;",
      "",
    ].join("\n");
  }
  return { files, missing: [...new Set(missing)] };
}
