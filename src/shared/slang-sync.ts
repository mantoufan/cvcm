import { LOCALES, type Locale } from "./locale";
import { SLANG_ENTRIES } from "./slang";

/**
 * What `npm run slang:sync` writes, as { path relative to the repo root: file content }. Pure, so tests/slang.test.ts
 * can rebuild the same files and fail when the committed copies are stale. A locale file that does not exist yet
 * falls back to English here (the sync warns); tests/slang.test.ts still requires every locale × entry on disk.
 *
 * - `src/locales/slang/index/<locale>.json`: every entry's name and blurb, so hub lists and related links need no entry chunk
 * - `src/locales/slang/all.ts`: every entry in every locale, for the Worker, prerender and tests
 * - `src/locales/slang/loaders/<locale>.ts`: one lazy chunk per entry, for the client
 * - `src/locales/packs/slang-<locale>.ts`: the slang pack (hub copy + list + meme data), loaded only on slang pages
 */
export function slangSyncFiles(read: (path: string) => string | null): { files: Record<string, string>; missing: string[] } {
  const files: Record<string, string> = {};
  const missing: string[] = [];
  const header = "// Generated by `npm run slang:sync`; do not edit.";

  /** Which locale's file stands in for `<locale>/<id>.json` (or `<locale>.json` when id is null). */
  const sourceLocale = (locale: Locale, id: string | null): Locale => {
    const path = id ? `src/locales/slang/${locale}/${id}.json` : `src/locales/slang/${locale}.json`;
    if (locale === "en" || read(path) !== null) return locale;
    missing.push(path);
    return "en";
  };
  const entryOf = (locale: Locale, id: string): { name: string; blurb: string } => {
    const text = read(`src/locales/slang/${locale}/${id}.json`);
    if (text === null) throw new Error(`slang:sync: missing src/locales/slang/${locale}/${id}.json`);
    const copy = JSON.parse(text) as { name: string; blurb: string };
    return { name: copy.name, blurb: copy.blurb };
  };

  const sources = Object.fromEntries(LOCALES.map((locale) => [locale, Object.fromEntries(SLANG_ENTRIES.map((id) => [id, sourceLocale(locale, id)]))])) as Record<Locale, Record<string, Locale>>;
  for (const locale of LOCALES) {
    const list = Object.fromEntries(SLANG_ENTRIES.map((id) => [id, entryOf(sources[locale][id], id)]));
    files[`src/locales/slang/index/${locale}.json`] = JSON.stringify(list, null, 2) + "\n";
  }

  const ident = (locale: string, id: string): string => `${locale.replace("-", "")}_${id.replace(/-/g, "_")}`;
  files["src/locales/slang/all.ts"] = [
    `${header} Every entry in every locale, for the Worker, prerender and tests; the client loads one at a time.`,
    ...LOCALES.flatMap((locale) => SLANG_ENTRIES.map((id) => `import ${ident(locale, id)} from "./${sources[locale][id]}/${id}.json";`)),
    'import type { SlangEntryCopy } from "../../shared/slang-i18n";',
    'import type { SlangId } from "../../shared/slang";',
    'import type { Locale } from "../../shared/locale";',
    "",
    "const all = {",
    ...LOCALES.map((locale) => `  ${JSON.stringify(locale)}: { ${SLANG_ENTRIES.map((id) => `${JSON.stringify(id)}: ${ident(locale, id)}`).join(", ")} },`),
    "} satisfies Record<Locale, Record<SlangId, unknown>>;",
    "",
    "// JSON imports type each block union loosely; the shape is checked by tests/slang.test.ts.",
    "export const SLANG_ALL = all as unknown as Record<Locale, Record<SlangId, SlangEntryCopy>>;",
    "",
  ].join("\n");

  // Plain dynamic imports (not import.meta.glob): the prerender bundles the client with esbuild, which has no glob.
  for (const locale of LOCALES) {
    files[`src/locales/slang/loaders/${locale}.ts`] = [
      `${header} One lazy chunk per slang entry in this locale, for the client.`,
      'import type { SlangId } from "../../../shared/slang";',
      "",
      "export const SLANG_LOADERS = {",
      ...SLANG_ENTRIES.map((id) => `  ${JSON.stringify(id)}: () => import("../${sources[locale][id]}/${id}.json"),`),
      "} satisfies Record<SlangId, () => Promise<unknown>>;",
      "",
    ].join("\n");
    files[`src/locales/packs/slang-${locale}.ts`] = [
      `${header} Slang hub copy, entry names and blurbs, loaded only on /memes/ pages.`,
      `import hub from "../slang/${sourceLocale(locale, null)}.json";`,
      `import list from "../slang/index/${locale}.json";`,
      // The daily snapshot rides in the slang pack, not the main bundle. zh-CN never shows coin data, so its pack does not
      // even carry the quotes (see showsCoins).
      'import trends from "../../shared/meme-trends.json";',
      'import images from "../../shared/meme-images.json";',
      ...(locale === "zh-CN" ? [] : ['import coins from "../../shared/meme-coins.json";']),
      'import type { SlangMessages } from "../../shared/messages";',
      'import type { MemeData, MemeImages } from "../../shared/slang-i18n";',
      "",
      locale === "zh-CN"
        ? "export default { ...hub, list, memes: { ...trends, coins: {}, coinsAsOf: null } as MemeData, images: images as MemeImages } satisfies SlangMessages;"
        : "export default { ...hub, list, memes: { ...trends, ...coins } as MemeData, images: images as MemeImages } satisfies SlangMessages;",
      "",
    ].join("\n");
  }
  return { files, missing: [...new Set(missing)] };
}
