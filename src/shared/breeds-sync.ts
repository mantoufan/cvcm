import { LOCALES, type Locale } from "./locale";
import { BREED_IDS } from "./breeds";

/**
 * What `npm run breeds:sync` writes, as { path relative to the repo root: file content }. Pure, so tests/breeds.test.ts
 * can rebuild the same files and fail when the committed copies are stale. A locale file that does not exist yet falls
 * back to English here (the sync warns); the test still requires every locale × breed on disk.
 *
 * - `src/locales/breeds/index/<locale>.json`: every breed's blurb, so the hub and related links need no breed chunk
 * - `src/locales/breeds/all.ts`: every breed in every locale, for the Worker, prerender and tests
 * - `src/locales/breeds/loaders/<locale>.ts`: one lazy chunk per breed, for the client
 * - `src/locales/packs/breeds-<locale>.ts`: the breeds pack (hub copy, names, blurbs, facts), loaded only on breed pages
 */
export function breedsSyncFiles(read: (path: string) => string | null): { files: Record<string, string>; missing: string[] } {
  const files: Record<string, string> = {};
  const missing: string[] = [];
  const header = "// Generated by `npm run breeds:sync`; do not edit.";
  const entryPath = (locale: Locale, id: string): string => `src/locales/breeds/${locale}/${id}.json`;

  const sourceLocale = (locale: Locale, id: string | null): Locale => {
    const path = id ? entryPath(locale, id) : `src/locales/breeds/${locale}.json`;
    if (read(path) !== null) return locale;
    if (locale === "en") throw new Error(`breeds:sync: missing ${path} (English is the master)`);
    missing.push(path);
    return "en";
  };
  const sources = Object.fromEntries(LOCALES.map((locale) => [locale, Object.fromEntries(BREED_IDS.map((id) => [id, sourceLocale(locale, id)]))])) as Record<Locale, Record<string, Locale>>;
  for (const locale of LOCALES) {
    const list = Object.fromEntries(BREED_IDS.map((id) => [id, (JSON.parse(read(entryPath(sources[locale][id], id))!) as { blurb: string }).blurb]));
    files[`src/locales/breeds/index/${locale}.json`] = JSON.stringify(list, null, 1) + "\n";
  }

  const ident = (locale: string, id: string): string => `${locale.replace("-", "")}_${id.replace(/[/-]/g, "_")}`;
  files["src/locales/breeds/all.ts"] = [
    `${header} Every breed in every locale, for the Worker, prerender and tests; the client loads one at a time.`,
    ...LOCALES.flatMap((locale) => BREED_IDS.map((id) => `import ${ident(locale, id)} from "./${sources[locale][id]}/${id}.json";`)),
    'import type { BreedEntryCopy } from "../../shared/breeds-store";',
    'import type { BreedId } from "../../shared/breeds";',
    'import type { Locale } from "../../shared/locale";',
    "",
    "const all = {",
    ...LOCALES.map((locale) => `  ${JSON.stringify(locale)}: { ${BREED_IDS.map((id) => `${JSON.stringify(id)}: ${ident(locale, id)}`).join(", ")} },`),
    "} satisfies Record<Locale, Record<BreedId, unknown>>;",
    "",
    "// JSON imports type each block union loosely; the shape is checked by tests/breeds.test.ts.",
    "export const BREEDS_ALL = all as unknown as Record<Locale, Record<BreedId, BreedEntryCopy>>;",
    "",
  ].join("\n");

  // Plain dynamic imports (not import.meta.glob): the prerender bundles the client with esbuild, which has no glob.
  for (const locale of LOCALES) {
    files[`src/locales/breeds/loaders/${locale}.ts`] = [
      `${header} One lazy chunk per breed in this locale, for the client.`,
      'import type { BreedId } from "../../../shared/breeds";',
      "",
      "export const BREED_LOADERS = {",
      ...BREED_IDS.map((id) => `  ${JSON.stringify(id)}: () => import("../${sources[locale][id]}/${id}.json"),`),
      "} satisfies Record<BreedId, () => Promise<unknown>>;",
      "",
    ].join("\n");
    files[`src/locales/packs/breeds-${locale}.ts`] = [
      `${header} Breeds hub copy, names, blurbs and facts, loaded only on /breeds/ pages.`,
      `import hub from "../breeds/${sourceLocale(locale, null)}.json";`,
      `import names from "../breeds/names/${locale}.json";`,
      'import english from "../breeds/names/en.json";',
      `import list from "../breeds/index/${locale}.json";`,
      // Facts ride in the pack (one shared chunk), not the breed chunks.
      'import data from "../../shared/breeds-data.json";',
      'import images from "../../shared/breeds-images.json";',
      'import type { BreedImage } from "../../shared/breeds-i18n";',
      'import type { BreedFacts, BreedsMessages } from "../../shared/breeds-store";',
      'import type { BreedId } from "../../shared/breeds";',
      "",
      "export default {",
      "  ...hub,",
      "  names: names as Record<BreedId, string>,",
      "  english: english as Record<BreedId, string>,",
      "  list: list as Record<BreedId, string>,",
      "  data: data as unknown as Record<BreedId, BreedFacts>,",
      "  images: images as Partial<Record<BreedId, BreedImage>>,",
      "} satisfies BreedsMessages;",
      "",
    ].join("\n");
  }
  return { files, missing: [...new Set(missing)] };
}
